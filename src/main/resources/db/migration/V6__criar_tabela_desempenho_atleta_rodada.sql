CREATE TABLE desempenho_atleta_rodada (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          atleta_id BIGINT NOT NULL,
                                          temporada INTEGER NOT NULL,
                                          rodada INTEGER NOT NULL,
                                          clube_id BIGINT,
                                          posicao_id INTEGER,
                                          pontos NUMERIC,
                                          entrou_em_campo BOOLEAN,
                                          scout JSONB,
                                          atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,

                                          CONSTRAINT fk_desempenho_atleta
                                              FOREIGN KEY (atleta_id) REFERENCES atleta(id),

                                          CONSTRAINT uk_desempenho_temporada_rodada_atleta
                                              UNIQUE (temporada, rodada, atleta_id),

                                          CONSTRAINT ck_desempenho_rodada_positiva
                                              CHECK (rodada > 0)
);