CREATE TABLE escalacao (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           temporada INTEGER NOT NULL,
                           time_id BIGINT NOT NULL,
                           rodada INTEGER NOT NULL,
                           capitao_id BIGINT,
                           reserva_luxo_id BIGINT,
                           esquema_id INTEGER,
                           pontos NUMERIC,
                           patrimonio NUMERIC,
                           atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,

                           CONSTRAINT uk_escalacao_temporada_time_rodada
                               UNIQUE (temporada, time_id, rodada),

                           CONSTRAINT ck_escalacao_rodada_positiva
                               CHECK (rodada > 0)
);