CREATE TABLE atleta_escalado (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 escalacao_id BIGINT NOT NULL,
                                 atleta_id BIGINT NOT NULL,
                                 apelido VARCHAR(255),
                                 clube_id BIGINT,
                                 posicao_id INTEGER,
                                 pontos NUMERIC,
                                 media NUMERIC,
                                 preco NUMERIC,
                                 jogos INTEGER,
                                 entrou_em_campo BOOLEAN,
                                 origem VARCHAR(20) NOT NULL,
                                 scout JSONB,

                                 CONSTRAINT fk_atleta_escalado_escalacao
                                     FOREIGN KEY (escalacao_id)
                                         REFERENCES escalacao (id),

                                 CONSTRAINT uk_atleta_escalado_origem
                                     UNIQUE (escalacao_id, atleta_id, origem),

                                 CONSTRAINT ck_atleta_escalado_origem
                                     CHECK (origem IN ('ATLETAS', 'RESERVAS'))
);