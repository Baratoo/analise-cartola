CREATE TABLE importacao_desempenho (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       temporada INTEGER NOT NULL,
                                       rodada INTEGER NOT NULL,
                                       quantidade_atletas INTEGER NOT NULL,
                                       consolidada BOOLEAN NOT NULL DEFAULT FALSE,
                                       atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,

                                       CONSTRAINT uk_importacao_desempenho_temporada_rodada
                                           UNIQUE (temporada, rodada),

                                       CONSTRAINT ck_importacao_desempenho_rodada_positiva
                                           CHECK (rodada > 0),

                                       CONSTRAINT ck_importacao_desempenho_quantidade
                                           CHECK (quantidade_atletas >= 0)
);